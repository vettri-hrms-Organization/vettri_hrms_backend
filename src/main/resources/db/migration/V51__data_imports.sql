-- Data import hub (com.haodaone.imports): an audit trail of import batches, the opening leave balances
-- written by the leave-balance import (for idempotent re-imports), and opening payroll YTD figures for
-- employees whose salary was paid outside Vettri earlier in the financial year (used by TDS / Form 16).

CREATE TABLE IF NOT EXISTS data_import_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT REFERENCES company(id),
    import_type VARCHAR(40) NOT NULL,
    file_name VARCHAR(255),
    file_hash VARCHAR(64),
    mode VARCHAR(20) NOT NULL,
    options VARCHAR(255),
    total_rows INTEGER NOT NULL DEFAULT 0,
    imported_rows INTEGER NOT NULL DEFAULT 0,
    skipped_rows INTEGER NOT NULL DEFAULT 0,
    failed_rows INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL,
    summary VARCHAR(1000),
    error_report TEXT,
    imported_by_name VARCHAR(150)
);
CREATE INDEX IF NOT EXISTS ix_data_import_batch_company ON data_import_batch (company_id, import_type, created_at);
CREATE INDEX IF NOT EXISTS ix_data_import_batch_hash ON data_import_batch (company_id, import_type, file_hash);

CREATE TABLE IF NOT EXISTS opening_leave_balance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT REFERENCES company(id),
    batch_id BIGINT NOT NULL REFERENCES data_import_batch(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    leave_type_id BIGINT NOT NULL REFERENCES leave_type(id),
    leave_year INTEGER NOT NULL,
    opening_days DOUBLE PRECISION NOT NULL,
    apply_mode VARCHAR(20) NOT NULL,
    applied_days DOUBLE PRECISION NOT NULL DEFAULT 0,
    previous_carried_days DOUBLE PRECISION,
    adjustment_id BIGINT REFERENCES leave_balance_adjustment(id)
);
CREATE INDEX IF NOT EXISTS ix_opening_leave_balance_key ON opening_leave_balance (company_id, employee_id, leave_type_id, leave_year);
CREATE UNIQUE INDEX IF NOT EXISTS ux_opening_leave_balance_active
    ON opening_leave_balance (employee_id, leave_type_id, leave_year) WHERE deleted = FALSE;

CREATE TABLE IF NOT EXISTS payroll_opening_ytd (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    batch_id BIGINT REFERENCES data_import_batch(id),
    financial_year INTEGER NOT NULL,
    gross_salary NUMERIC(14, 2) NOT NULL DEFAULT 0,
    taxable_salary NUMERIC(14, 2) NOT NULL DEFAULT 0,
    pf_employee NUMERIC(14, 2) NOT NULL DEFAULT 0,
    professional_tax NUMERIC(14, 2) NOT NULL DEFAULT 0,
    tds_deducted NUMERIC(14, 2) NOT NULL DEFAULT 0,
    months_covered INTEGER NOT NULL DEFAULT 0,
    previous_employer_income NUMERIC(14, 2) NOT NULL DEFAULT 0,
    previous_employer_tds NUMERIC(14, 2) NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_payroll_opening_ytd_company ON payroll_opening_ytd (company_id, financial_year);
CREATE UNIQUE INDEX IF NOT EXISTS ux_payroll_opening_ytd_active
    ON payroll_opening_ytd (employee_id, financial_year) WHERE deleted = FALSE;
