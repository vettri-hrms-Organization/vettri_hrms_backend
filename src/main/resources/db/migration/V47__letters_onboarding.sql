-- HR letters (templates, letterhead, issued letters) and onboarding /
-- offboarding checklists. Every table carries the BaseEntity audit
-- columns and a company_id for tenant isolation.

CREATE TABLE IF NOT EXISTS letter_template (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    letter_type VARCHAR(40) NOT NULL,
    name VARCHAR(150) NOT NULL,
    title VARCHAR(200) NOT NULL,
    body TEXT NOT NULL,
    built_in BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX IF NOT EXISTS idx_letter_template_company ON letter_template(company_id);

CREATE TABLE IF NOT EXISTS letterhead_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    logo_s3_key VARCHAR(500),
    logo_content_type VARCHAR(60),
    address VARCHAR(1000),
    signatory_name VARCHAR(150),
    signatory_designation VARCHAR(150),
    footer VARCHAR(500)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_letterhead_settings_company ON letterhead_settings(company_id) WHERE deleted = FALSE;

CREATE TABLE IF NOT EXISTS issued_letter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    template_id BIGINT REFERENCES letter_template(id),
    employee_id BIGINT REFERENCES employee(id),
    candidate_id BIGINT,
    letter_type VARCHAR(40) NOT NULL,
    title VARCHAR(200) NOT NULL,
    rendered_body TEXT,
    s3_object_key VARCHAR(500),
    file_name VARCHAR(255),
    file_size_bytes BIGINT,
    employee_document_id BIGINT,
    issued_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    issued_by VARCHAR(150),
    emailed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    email_status VARCHAR(20)
);
CREATE INDEX IF NOT EXISTS idx_issued_letter_company ON issued_letter(company_id);
CREATE INDEX IF NOT EXISTS idx_issued_letter_employee ON issued_letter(employee_id);
CREATE INDEX IF NOT EXISTS idx_issued_letter_candidate ON issued_letter(candidate_id);

CREATE TABLE IF NOT EXISTS checklist_template (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    name VARCHAR(150) NOT NULL,
    template_type VARCHAR(20) NOT NULL,
    description VARCHAR(1000),
    default_template BOOLEAN NOT NULL DEFAULT FALSE,
    auto_start BOOLEAN NOT NULL DEFAULT TRUE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX IF NOT EXISTS idx_checklist_template_company ON checklist_template(company_id);

CREATE TABLE IF NOT EXISTS checklist_template_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    template_id BIGINT NOT NULL REFERENCES checklist_template(id),
    title VARCHAR(200) NOT NULL,
    description VARCHAR(1000),
    owner_type VARCHAR(20) NOT NULL,
    owner_user_id BIGINT REFERENCES app_user(id),
    due_offset_days INTEGER NOT NULL DEFAULT 0,
    requires_document BOOLEAN NOT NULL DEFAULT FALSE,
    document_type VARCHAR(40),
    link_key VARCHAR(40),
    sort_order INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_checklist_template_task_template ON checklist_template_task(template_id);

CREATE TABLE IF NOT EXISTS employee_checklist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    template_id BIGINT REFERENCES checklist_template(id),
    checklist_type VARCHAR(20) NOT NULL,
    name VARCHAR(150) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS',
    anchor_date DATE NOT NULL,
    started_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    completed_at TIMESTAMP(6) WITHOUT TIME ZONE
);
CREATE INDEX IF NOT EXISTS idx_employee_checklist_company ON employee_checklist(company_id, status);
CREATE INDEX IF NOT EXISTS idx_employee_checklist_employee ON employee_checklist(employee_id);

CREATE TABLE IF NOT EXISTS employee_checklist_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    checklist_id BIGINT NOT NULL REFERENCES employee_checklist(id),
    title VARCHAR(200) NOT NULL,
    description VARCHAR(1000),
    owner_type VARCHAR(20) NOT NULL,
    owner_user_id BIGINT REFERENCES app_user(id),
    owner_employee_id BIGINT REFERENCES employee(id),
    due_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    completed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    completed_by VARCHAR(150),
    remarks VARCHAR(1000),
    requires_document BOOLEAN NOT NULL DEFAULT FALSE,
    document_type VARCHAR(40),
    document_id BIGINT,
    link_key VARCHAR(40),
    sort_order INTEGER NOT NULL DEFAULT 0,
    last_reminder_on DATE
);
CREATE INDEX IF NOT EXISTS idx_employee_checklist_task_checklist ON employee_checklist_task(checklist_id);
CREATE INDEX IF NOT EXISTS idx_employee_checklist_task_due ON employee_checklist_task(company_id, status, due_date);
