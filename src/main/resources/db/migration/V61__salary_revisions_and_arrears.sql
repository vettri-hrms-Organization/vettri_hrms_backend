-- V61: salary revisions with arrears.
-- A revision records old and new pay from an effective date. Back-dated revisions compute arrears for months
-- already paid at the old rate; they are paid as one taxable line in a chosen payroll month. Future-dated
-- revisions wait and apply on their effective date. Additive only: new tables, no existing data changes.

CREATE TABLE IF NOT EXISTS salary_revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    revision_type VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    effective_from DATE NOT NULL,
    old_structure_id BIGINT,
    new_structure_id BIGINT,
    old_monthly_gross NUMERIC(14, 2) NOT NULL,
    new_monthly_gross NUMERIC(14, 2) NOT NULL,
    new_components_json TEXT NOT NULL,
    auto_statutory BOOLEAN NOT NULL DEFAULT TRUE,
    reason VARCHAR(1000),
    arrears_total NUMERIC(14, 2) NOT NULL DEFAULT 0,
    arrears_payout_month VARCHAR(7),
    arrears_status VARCHAR(20) NOT NULL,
    arrears_payroll_item_id BIGINT,
    applied_at TIMESTAMP(6) WITHOUT TIME ZONE,
    created_by_name VARCHAR(150)
);
CREATE INDEX IF NOT EXISTS ix_salary_revision_company ON salary_revision (company_id, status);
CREATE INDEX IF NOT EXISTS ix_salary_revision_employee ON salary_revision (employee_id, status);

CREATE TABLE IF NOT EXISTS salary_revision_arrear (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    revision_id BIGINT NOT NULL REFERENCES salary_revision(id),
    period VARCHAR(7) NOT NULL,
    paid_gross NUMERIC(14, 2) NOT NULL,
    revised_gross NUMERIC(14, 2) NOT NULL,
    amount NUMERIC(14, 2) NOT NULL,
    payroll_item_id BIGINT
);
CREATE INDEX IF NOT EXISTS ix_salary_revision_arrear_revision ON salary_revision_arrear (revision_id);
