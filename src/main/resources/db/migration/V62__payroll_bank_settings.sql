-- V62: company salary debit account, used to build bank transfer (bulk payment) files from a payroll run.
-- Additive only: one new table, no existing data changes.

CREATE TABLE IF NOT EXISTS payroll_bank_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    debit_account_number VARCHAR(34),
    debit_ifsc VARCHAR(11),
    bank_name VARCHAR(100),
    default_format VARCHAR(20) NOT NULL DEFAULT 'GENERIC',
    narration VARCHAR(30),
    CONSTRAINT uk_payroll_bank_settings_company UNIQUE (company_id)
);
