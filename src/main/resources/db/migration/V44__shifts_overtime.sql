-- Shifts, rosters, late marks and overtime.
--
-- work_shift          shift master per company (supports overnight shifts: end <= start).
-- shift_assignment    default shift per department / employee with an effective-from date.
-- shift_roster        employee x date -> shift or week off (rotational teams).
-- overtime_entry      one overtime claim per employee per day, approval workflow + payroll link.
-- attendance_shift_settings  per-company OT rate and late-mark penalty policy.

CREATE TABLE work_shift (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    name VARCHAR(100) NOT NULL,
    code VARCHAR(30) NOT NULL,
    start_time TIME WITHOUT TIME ZONE NOT NULL,
    end_time TIME WITHOUT TIME ZONE NOT NULL,
    break_minutes INTEGER NOT NULL DEFAULT 0,
    grace_in_minutes INTEGER NOT NULL DEFAULT 0,
    grace_out_minutes INTEGER NOT NULL DEFAULT 0,
    half_day_hours NUMERIC(4,2) NOT NULL DEFAULT 4,
    full_day_hours NUMERIC(4,2) NOT NULL DEFAULT 8,
    overtime_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    min_overtime_minutes INTEGER NOT NULL DEFAULT 30,
    color VARCHAR(20),
    company_default BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_work_shift_company ON work_shift(company_id, deleted);

CREATE TABLE shift_assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    shift_id BIGINT NOT NULL REFERENCES work_shift(id),
    department_id BIGINT REFERENCES department(id),
    employee_id BIGINT REFERENCES employee(id),
    effective_from DATE NOT NULL
);

CREATE INDEX idx_shift_assignment_company ON shift_assignment(company_id, deleted);

CREATE TABLE shift_roster (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    roster_date DATE NOT NULL,
    shift_id BIGINT REFERENCES work_shift(id),
    week_off BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_shift_roster_employee_date UNIQUE (employee_id, roster_date)
);

CREATE INDEX idx_shift_roster_company_date ON shift_roster(company_id, roster_date);

CREATE TABLE overtime_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    work_date DATE NOT NULL,
    shift_id BIGINT REFERENCES work_shift(id),
    shift_name VARCHAR(100),
    computed_minutes INTEGER NOT NULL DEFAULT 0,
    approved_minutes INTEGER,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    source VARCHAR(20) NOT NULL DEFAULT 'SYSTEM',
    employee_note VARCHAR(500),
    reviewed_by_employee_id BIGINT REFERENCES employee(id),
    reviewed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    review_note VARCHAR(500),
    hourly_rate NUMERIC(12,2),
    rate_multiplier NUMERIC(5,2),
    amount NUMERIC(12,2),
    payroll_item_id BIGINT,
    paid_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uk_overtime_employee_date UNIQUE (employee_id, work_date)
);

CREATE INDEX idx_overtime_company_status ON overtime_entry(company_id, status, work_date);

CREATE TABLE attendance_shift_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    overtime_rate_type VARCHAR(20) NOT NULL DEFAULT 'MULTIPLIER',
    overtime_multiplier NUMERIC(5,2) NOT NULL DEFAULT 1.5,
    overtime_flat_hourly_rate NUMERIC(12,2),
    late_penalty_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    late_marks_per_penalty INTEGER NOT NULL DEFAULT 3,
    late_penalty_days NUMERIC(4,2) NOT NULL DEFAULT 0.5,
    CONSTRAINT uk_attendance_shift_settings_company UNIQUE (company_id)
);

-- Every existing company gets the "General shift 09:30-18:30" as its default,
-- using the company's configured attendance grace period for late-in.
INSERT INTO work_shift (company_id, name, code, start_time, end_time, break_minutes, grace_in_minutes,
                        grace_out_minutes, half_day_hours, full_day_hours, overtime_enabled,
                        min_overtime_minutes, color, company_default, active)
SELECT c.id, 'General shift', 'GEN', TIME '09:30', TIME '18:30', 60, COALESCE(c.attendance_grace_minutes, 10),
       0, 4, 8, FALSE, 30, '#2563eb', TRUE, TRUE
FROM company c
WHERE NOT EXISTS (SELECT 1 FROM work_shift s WHERE s.company_id = c.id AND s.company_default = TRUE AND s.deleted = FALSE);
