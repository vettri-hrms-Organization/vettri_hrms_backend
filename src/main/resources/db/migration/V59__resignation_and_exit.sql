-- V59: employee-initiated resignation (Keka-style).
-- Employee resigns -> reporting manager reviews -> HR accepts with the final last working day ->
-- employee serves notice (status Resigned with a future last working date; login ends after it) ->
-- exit interview. Additive only: new tables, no existing data changes.

CREATE TABLE IF NOT EXISTS exit_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    notice_period_days INTEGER NOT NULL DEFAULT 30,
    manager_approval BOOLEAN NOT NULL DEFAULT TRUE,
    exit_interview BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_exit_settings_company UNIQUE (company_id)
);

CREATE TABLE IF NOT EXISTS employee_resignation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    status VARCHAR(30) NOT NULL,
    reason_category VARCHAR(40) NOT NULL,
    reason VARCHAR(2000),
    resignation_date DATE NOT NULL,
    notice_period_days INTEGER NOT NULL,
    policy_last_working_date DATE NOT NULL,
    requested_last_working_date DATE,
    approved_last_working_date DATE,
    manager_employee_id BIGINT,
    manager_decision_by VARCHAR(150),
    manager_decision_at TIMESTAMP(6) WITHOUT TIME ZONE,
    manager_note VARCHAR(1000),
    manager_recommended_last_working_date DATE,
    hr_decision_by VARCHAR(150),
    hr_decision_at TIMESTAMP(6) WITHOUT TIME ZONE,
    hr_note VARCHAR(1000),
    withdrawn_at TIMESTAMP(6) WITHOUT TIME ZONE,
    interview_answers TEXT,
    interview_completed_at TIMESTAMP(6) WITHOUT TIME ZONE
);
CREATE INDEX IF NOT EXISTS ix_employee_resignation_company ON employee_resignation (company_id, status);
CREATE INDEX IF NOT EXISTS ix_employee_resignation_employee ON employee_resignation (employee_id, status);
