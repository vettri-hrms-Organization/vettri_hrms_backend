-- V68: Phase D platform - Slack/Teams posts, outbound webhooks, public API keys, personal ICS calendar feeds,
-- saved custom reports, and project billing (rates on timesheet projects, invoices from approved billable hours).
-- Additive only: new columns (nullable) and new tables; no existing data is changed.

ALTER TABLE timesheet_project ADD COLUMN IF NOT EXISTS billing_rate NUMERIC(12, 2);
ALTER TABLE timesheet_project ADD COLUMN IF NOT EXISTS member_rates_json TEXT;
ALTER TABLE timesheet_entry ADD COLUMN IF NOT EXISTS invoice_id BIGINT;

CREATE TABLE IF NOT EXISTS integration_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100), updated_by VARCHAR(100), deleted BOOLEAN NOT NULL DEFAULT FALSE, deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    slack_webhook_enc TEXT,
    teams_webhook_enc TEXT,
    events_json TEXT NOT NULL,
    last_error VARCHAR(300),
    last_posted_at TIMESTAMP(6) WITHOUT TIME ZONE
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_integration_settings_company ON integration_settings (company_id) WHERE deleted = FALSE;

CREATE TABLE IF NOT EXISTS webhook_endpoint (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100), updated_by VARCHAR(100), deleted BOOLEAN NOT NULL DEFAULT FALSE, deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    url VARCHAR(500) NOT NULL,
    description VARCHAR(200),
    secret_enc TEXT NOT NULL,
    events_json TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    last_status INT,
    last_error VARCHAR(300),
    last_delivery_at TIMESTAMP(6) WITHOUT TIME ZONE,
    failure_count INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS api_key (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100), updated_by VARCHAR(100), deleted BOOLEAN NOT NULL DEFAULT FALSE, deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    name VARCHAR(100) NOT NULL,
    prefix VARCHAR(16) NOT NULL,
    key_hash VARCHAR(64) NOT NULL,
    scopes_json TEXT NOT NULL,
    created_by_name VARCHAR(150),
    last_used_at TIMESTAMP(6) WITHOUT TIME ZONE,
    revoked_at TIMESTAMP(6) WITHOUT TIME ZONE,
    expires_on DATE
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_api_key_hash ON api_key (key_hash);

CREATE TABLE IF NOT EXISTS calendar_feed (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100), updated_by VARCHAR(100), deleted BOOLEAN NOT NULL DEFAULT FALSE, deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    token_hash VARCHAR(64) NOT NULL,
    token_enc TEXT NOT NULL,
    last_fetched_at TIMESTAMP(6) WITHOUT TIME ZONE
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_calendar_feed_token ON calendar_feed (token_hash);
CREATE UNIQUE INDEX IF NOT EXISTS ux_calendar_feed_employee ON calendar_feed (employee_id) WHERE deleted = FALSE;

CREATE TABLE IF NOT EXISTS saved_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100), updated_by VARCHAR(100), deleted BOOLEAN NOT NULL DEFAULT FALSE, deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    name VARCHAR(120) NOT NULL,
    dataset VARCHAR(30) NOT NULL,
    definition_json TEXT NOT NULL,
    created_by_name VARCHAR(150),
    owner_user_id BIGINT NOT NULL,
    shared BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS project_invoice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100), updated_by VARCHAR(100), deleted BOOLEAN NOT NULL DEFAULT FALSE, deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    project_id BIGINT NOT NULL REFERENCES timesheet_project(id),
    invoice_number VARCHAR(30) NOT NULL,
    period_from DATE NOT NULL,
    period_to DATE NOT NULL,
    status VARCHAR(10) NOT NULL,
    lines_json TEXT NOT NULL,
    subtotal NUMERIC(14, 2) NOT NULL,
    tax_percent NUMERIC(5, 2) NOT NULL DEFAULT 0,
    tax_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total NUMERIC(14, 2) NOT NULL,
    notes VARCHAR(1000),
    created_by_name VARCHAR(150),
    sent_at TIMESTAMP(6) WITHOUT TIME ZONE,
    paid_at TIMESTAMP(6) WITHOUT TIME ZONE
);
CREATE INDEX IF NOT EXISTS ix_project_invoice_project ON project_invoice (company_id, project_id);
