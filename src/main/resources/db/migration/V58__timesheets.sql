-- V58: timesheets (Keka-style).
-- Projects (optionally billable, with members and tasks), daily time entries, weekly submission with
-- manager approval, and per-company settings. Additive only: new tables, no existing data changes.

CREATE TABLE IF NOT EXISTS timesheet_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    weekly_target_minutes INTEGER NOT NULL DEFAULT 2400,
    require_notes BOOLEAN NOT NULL DEFAULT FALSE,
    prompt_on_checkout BOOLEAN NOT NULL DEFAULT TRUE,
    daily_reminder BOOLEAN NOT NULL DEFAULT TRUE,
    weekly_reminder BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_timesheet_settings_company UNIQUE (company_id)
);

CREATE TABLE IF NOT EXISTS timesheet_project (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    name VARCHAR(150) NOT NULL,
    code VARCHAR(30),
    client_name VARCHAR(150),
    description VARCHAR(1000),
    billable BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    start_date DATE,
    end_date DATE,
    budget_minutes INTEGER,
    all_employees BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS ix_timesheet_project_company ON timesheet_project (company_id, status);

CREATE TABLE IF NOT EXISTS timesheet_project_member (
    project_id BIGINT NOT NULL REFERENCES timesheet_project(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    PRIMARY KEY (project_id, employee_id)
);
CREATE INDEX IF NOT EXISTS ix_timesheet_project_member_employee ON timesheet_project_member (employee_id);

CREATE TABLE IF NOT EXISTS timesheet_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    project_id BIGINT NOT NULL REFERENCES timesheet_project(id),
    name VARCHAR(150) NOT NULL,
    billable BOOLEAN,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX IF NOT EXISTS ix_timesheet_task_project ON timesheet_task (project_id, deleted);

CREATE TABLE IF NOT EXISTS timesheet_week (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    week_start DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    total_minutes INTEGER NOT NULL DEFAULT 0,
    submitted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    reviewed_by_user_id BIGINT,
    reviewed_by_name VARCHAR(150),
    review_note VARCHAR(500),
    reviewed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uk_timesheet_week_employee UNIQUE (employee_id, week_start)
);
CREATE INDEX IF NOT EXISTS ix_timesheet_week_company ON timesheet_week (company_id, status, week_start);

CREATE TABLE IF NOT EXISTS timesheet_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    work_date DATE NOT NULL,
    project_id BIGINT REFERENCES timesheet_project(id),
    task_id BIGINT REFERENCES timesheet_task(id),
    minutes INTEGER NOT NULL,
    notes VARCHAR(1000),
    billable BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS ix_timesheet_entry_employee_date ON timesheet_entry (employee_id, work_date, deleted);
CREATE INDEX IF NOT EXISTS ix_timesheet_entry_company_date ON timesheet_entry (company_id, work_date, deleted);
CREATE INDEX IF NOT EXISTS ix_timesheet_entry_project ON timesheet_entry (project_id, work_date);
