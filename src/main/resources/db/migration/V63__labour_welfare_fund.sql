-- V63: Labour Welfare Fund. Per-company, per-state rules (HR-editable; seeded from defaults when a state is added)
-- and the contributions actually deducted, with the employer share, for the LWF return.
-- Additive only: new tables, no existing data changes.

CREATE TABLE IF NOT EXISTS lwf_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    state_code VARCHAR(5) NOT NULL,
    state_name VARCHAR(60) NOT NULL,
    deduction_months VARCHAR(40) NOT NULL,
    employee_fixed NUMERIC(10, 2) NOT NULL DEFAULT 0,
    employee_percent NUMERIC(6, 3) NOT NULL DEFAULT 0,
    employee_max NUMERIC(10, 2),
    employer_fixed NUMERIC(10, 2) NOT NULL DEFAULT 0,
    employer_multiplier NUMERIC(6, 3) NOT NULL DEFAULT 0,
    min_wages NUMERIC(14, 2),
    max_wages NUMERIC(14, 2),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_lwf_rule_company_state UNIQUE (company_id, state_code)
);

CREATE TABLE IF NOT EXISTS lwf_contribution (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    payroll_item_id BIGINT NOT NULL,
    period VARCHAR(7) NOT NULL,
    state_code VARCHAR(5) NOT NULL,
    wages NUMERIC(14, 2) NOT NULL,
    employee_amount NUMERIC(10, 2) NOT NULL,
    employer_amount NUMERIC(10, 2) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_lwf_contribution_period ON lwf_contribution (company_id, period);
CREATE INDEX IF NOT EXISTS ix_lwf_contribution_employee ON lwf_contribution (employee_id, period);
