-- V67: Phase C workflows - leave sandwich rule, multi-level leave approval chains, probation confirmation,
-- HR helpdesk, click-to-sign e-signatures, travel requests with advances, and surveys / polls / eNPS.
-- Additive only: new columns with defaults and new tables; no existing data is changed.

ALTER TABLE leave_type ADD COLUMN IF NOT EXISTS sandwich_rule BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE leave_request ADD COLUMN IF NOT EXISTS approval_level INT NOT NULL DEFAULT 0;
