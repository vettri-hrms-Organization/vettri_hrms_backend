-- V66: performance suite - review cycles (self/peer/manager/calibration), OKRs, 1:1 meetings, continuous feedback
-- (public praise = kudos wall), performance improvement plans and compensation planning.
-- Additive only: new tables, no existing data changes. Every table carries the BaseEntity audit columns.

CREATE TABLE IF NOT EXISTS performance_cycle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100), updated_by VARCHAR(100), deleted BOOLEAN NOT NULL DEFAULT FALSE, deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    name VARCHAR(120) NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    self_due DATE,
    manager_due DATE,
    peer_reviews BOOLEAN NOT NULL DEFAULT FALSE,
    created_by_name VARCHAR(150)
);
CREATE INDEX IF NOT EXISTS ix_performance_cycle_company ON performance_cycle (company_id, status);

CREATE TABLE IF NOT EXISTS cycle_participant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100), updated_by VARCHAR(100), deleted BOOLEAN NOT NULL DEFAULT FALSE, deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    cycle_id BIGINT NOT NULL REFERENCES performance_cycle(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    manager_employee_id BIGINT,
    status VARCHAR(20) NOT NULL,
    manager_rating NUMERIC(3, 1),
    final_rating NUMERIC(3, 1),
    calibration_note VARCHAR(1000),
    released_at TIMESTAMP(6) WITHOUT TIME ZONE,
    acknowledged_at TIMESTAMP(6) WITHOUT TIME ZONE
);
CREATE INDEX IF NOT EXISTS ix_cycle_participant_cycle ON cycle_participant (cycle_id);
CREATE INDEX IF NOT EXISTS ix_cycle_participant_employee ON cycle_participant (employee_id);

CREATE TABLE IF NOT EXISTS review_response (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100), updated_by VARCHAR(100), deleted BOOLEAN NOT NULL DEFAULT FALSE, deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    participant_id BIGINT NOT NULL REFERENCES cycle_participant(id),
    reviewer_employee_id BIGINT NOT NULL,
    kind VARCHAR(10) NOT NULL,
    status VARCHAR(12) NOT NULL,
    rating NUMERIC(3, 1),
    strengths TEXT,
    improvements TEXT,
    comments TEXT,
    submitted_at TIMESTAMP(6) WITHOUT TIME ZONE
);
CREATE INDEX IF NOT EXISTS ix_review_response_participant ON review_response (participant_id);
CREATE INDEX IF NOT EXISTS ix_review_response_reviewer ON review_response (reviewer_employee_id, status);

