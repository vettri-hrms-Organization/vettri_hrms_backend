-- V55: endpoint-agent auto-update and tray attendance breaks.
-- agent_release: platform-wide (not per company) list of published Vettri Agent setups. The agent
-- polls GET /api/agent/update and installs the single active release when it is newer than itself,
-- after checking the download's SHA-256.
-- attendance_break: Start/End break punches from the agent tray, tied to the day's attendance session.

CREATE TABLE IF NOT EXISTS agent_release (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    release_version VARCHAR(32) NOT NULL,
    download_url VARCHAR(1000) NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    release_notes VARCHAR(2000),
    active BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_agent_release_version ON agent_release (release_version) WHERE deleted = FALSE;
CREATE INDEX IF NOT EXISTS ix_agent_release_active ON agent_release (active, deleted);

CREATE TABLE IF NOT EXISTS attendance_break (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    attendance_session_id BIGINT NOT NULL REFERENCES attendance_session(id),
    started_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    ended_at TIMESTAMP(6) WITHOUT TIME ZONE,
    source VARCHAR(30) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_attendance_break_session ON attendance_break (attendance_session_id, deleted);
CREATE INDEX IF NOT EXISTS ix_attendance_break_employee_day ON attendance_break (company_id, employee_id, started_at);
