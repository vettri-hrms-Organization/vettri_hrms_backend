-- V56: customer-controlled support access.
-- Vettri platform staff (SUPER_ADMIN) can no longer open a company's HR data at will. A company admin
-- grants time-limited access (read-only by default); every grant, revoke and support session is audited.

CREATE TABLE IF NOT EXISTS support_access_grant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    granted_by_user_id BIGINT,
    granted_by_name VARCHAR(150),
    reason VARCHAR(500),
    access_level VARCHAR(20) NOT NULL,
    expires_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    revoked_at TIMESTAMP(6) WITHOUT TIME ZONE,
    revoked_by_name VARCHAR(150)
);
CREATE INDEX IF NOT EXISTS ix_support_access_grant_company ON support_access_grant (company_id, revoked_at, expires_at);
