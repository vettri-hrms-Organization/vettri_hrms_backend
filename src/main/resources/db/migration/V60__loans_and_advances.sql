-- V60: employee loans and salary advances, recovered through payroll.
-- payroll_item_deduction holds post-tax deduction lines on a payslip (loan EMI, advance recovery) that don't
-- touch gross, PF, ESI or TDS. Additive only: new tables, no existing data changes.

CREATE TABLE IF NOT EXISTS payroll_item_deduction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT REFERENCES company(id),
    payroll_item_id BIGINT NOT NULL REFERENCES payroll_item(id),
    code VARCHAR(50) NOT NULL,
    label VARCHAR(200) NOT NULL,
    amount NUMERIC(14, 2) NOT NULL,
    source_type VARCHAR(50),
    source_id BIGINT,
    settled BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS ix_payroll_item_deduction_item ON payroll_item_deduction (payroll_item_id);

CREATE TABLE IF NOT EXISTS employee_loan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    loan_type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    requested_amount NUMERIC(14, 2) NOT NULL,
    requested_months INTEGER NOT NULL,
    reason VARCHAR(1000),
    approved_amount NUMERIC(14, 2),
    tenure_months INTEGER,
    annual_interest_rate NUMERIC(6, 3),
    emi_amount NUMERIC(14, 2),
    first_deduction_month VARCHAR(7),
    disburse_via_payroll BOOLEAN NOT NULL DEFAULT FALSE,
    disbursed_on DATE,
    disbursement_reference VARCHAR(100),
    disbursal_settled BOOLEAN NOT NULL DEFAULT FALSE,
    reviewed_by VARCHAR(150),
    reviewed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    review_note VARCHAR(1000),
    closed_on DATE
);
CREATE INDEX IF NOT EXISTS ix_employee_loan_company ON employee_loan (company_id, status);
CREATE INDEX IF NOT EXISTS ix_employee_loan_employee ON employee_loan (employee_id, status);

CREATE TABLE IF NOT EXISTS employee_loan_installment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    loan_id BIGINT NOT NULL REFERENCES employee_loan(id),
    sequence_no INTEGER NOT NULL,
    due_month VARCHAR(7) NOT NULL,
    principal NUMERIC(14, 2) NOT NULL,
    interest NUMERIC(14, 2) NOT NULL,
    amount NUMERIC(14, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    payroll_item_id BIGINT,
    paid_on DATE,
    note VARCHAR(300)
);
CREATE INDEX IF NOT EXISTS ix_employee_loan_installment_loan ON employee_loan_installment (loan_id, sequence_no);
CREATE INDEX IF NOT EXISTS ix_employee_loan_installment_due ON employee_loan_installment (company_id, status, due_month);
