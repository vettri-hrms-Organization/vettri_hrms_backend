-- ------------------------------------------- gapless invoice number counters
-- One row per series (e.g. "INV:2026-27", "CN:2026-27"); the row is locked
-- (SELECT ... FOR UPDATE) while a number is taken, inside the same
-- transaction that issues the invoice, so a rollback never leaves a gap.
CREATE TABLE IF NOT EXISTS billing_invoice_counter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    series VARCHAR(40) NOT NULL,
    last_value BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_billing_invoice_counter_series UNIQUE (series)
);

INSERT INTO billing_invoice_counter (series, last_value) VALUES
    ('INV:2026-27', 0), ('INV:2027-28', 0), ('INV:2028-29', 0),
    ('CN:2026-27', 0), ('CN:2027-28', 0), ('CN:2028-29', 0)
ON CONFLICT (series) DO NOTHING;

-- ------------------------------------------------------ prorated seat add-ons
CREATE TABLE IF NOT EXISTS billing_seat_addon (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    subscription_id BIGINT NOT NULL REFERENCES subscription(id),
    seats INTEGER NOT NULL,
    effective_date DATE NOT NULL,
    period_end DATE NOT NULL,
    days_remaining INTEGER NOT NULL,
    period_days INTEGER NOT NULL,
    unit_rate NUMERIC(12,2) NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    invoice_id BIGINT REFERENCES billing_invoice(id)
);

CREATE INDEX IF NOT EXISTS ix_billing_seat_addon_sub ON billing_seat_addon(subscription_id, invoice_id);

-- --------------------------------------------- idempotent webhook processing
CREATE TABLE IF NOT EXISTS billing_webhook_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    event_key VARCHAR(150) NOT NULL,
    event_type VARCHAR(100),
    processed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uk_billing_webhook_event_key UNIQUE (event_key)
);
