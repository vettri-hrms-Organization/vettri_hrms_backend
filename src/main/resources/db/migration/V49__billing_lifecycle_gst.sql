-- Subscription lifecycle (trial -> active -> past due -> suspended), renewal
-- payments, prorated seat add-ons, GST tax invoices with a gapless
-- per-financial-year numbering counter, credit notes and idempotent webhooks.
--
-- MIGRATION SAFETY: the new daily lifecycle job (BillingScheduler) moves a
-- subscription to PAST_DUE once its renewal_date passes unpaid and suspends it
-- after the grace window. Existing subscriptions were never billed for
-- renewal, so many have a renewal_date in the past. To make sure deploying
-- this does NOT suspend anyone, every live ACTIVE / TRIALING / TRIAL
-- subscription gets renewal_date = GREATEST(renewal_date, CURRENT_DATE + 30):
-- every existing customer gets at least 30 days (and the T-7/T-3/T-1 reminder
-- emails) before the first renewal invoice falls due.

-- ---------------------------------------------------------------- subscription
ALTER TABLE subscription
    ADD COLUMN IF NOT EXISTS past_due_since DATE,
    ADD COLUMN IF NOT EXISTS grace_ends_on DATE,
    ADD COLUMN IF NOT EXISTS suspended_at TIMESTAMP(6) WITHOUT TIME ZONE,
    ADD COLUMN IF NOT EXISTS suspension_reason VARCHAR(50),
    ADD COLUMN IF NOT EXISTS pending_plan VARCHAR(50),
    ADD COLUMN IF NOT EXISTS pending_billing_cycle VARCHAR(20),
    ADD COLUMN IF NOT EXISTS period_peak_seats INTEGER,
    ADD COLUMN IF NOT EXISTS cancel_at_period_end BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS razorpay_subscription_id VARCHAR(100),
    ADD COLUMN IF NOT EXISTS razorpay_plan_id VARCHAR(100);

UPDATE subscription
   SET renewal_date = GREATEST(COALESCE(renewal_date, CURRENT_DATE), CURRENT_DATE + 30)
 WHERE deleted = FALSE
   AND status IN ('ACTIVE', 'TRIALING', 'TRIAL');

CREATE INDEX IF NOT EXISTS ix_subscription_status_renewal ON subscription(status, renewal_date);
CREATE INDEX IF NOT EXISTS ix_subscription_razorpay_sub ON subscription(razorpay_subscription_id);

