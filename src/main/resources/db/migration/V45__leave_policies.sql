-- Leave policies: accrual, carry-forward limits/expiry, encashment, comp-off and a manual-adjustment ledger.
-- Effective balances are computed on read (LeaveBalanceService); leave_balance rows are materialised by
-- LeavePolicyScheduler for audit/visibility and hold the year-end carry-forward.

ALTER TABLE leave_type ADD COLUMN IF NOT EXISTS accrual_mode VARCHAR(20) NOT NULL DEFAULT 'YEARLY_UPFRONT';
ALTER TABLE leave_type ADD COLUMN IF NOT EXISTS accrual_rounding VARCHAR(20) NOT NULL DEFAULT 'HALF_DAY';
ALTER TABLE leave_type ADD COLUMN IF NOT EXISTS prorate_on_joining BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE leave_type ADD COLUMN IF NOT EXISTS joining_cutoff_day INTEGER NULL;
ALTER TABLE leave_type ADD COLUMN IF NOT EXISTS max_balance_days DOUBLE PRECISION NULL;
ALTER TABLE leave_type ADD COLUMN IF NOT EXISTS probation_days INTEGER NULL;
ALTER TABLE leave_type ADD COLUMN IF NOT EXISTS negative_balance_days DOUBLE PRECISION NULL;
ALTER TABLE leave_type ADD COLUMN IF NOT EXISTS max_carry_forward_days DOUBLE PRECISION NULL;
ALTER TABLE leave_type ADD COLUMN IF NOT EXISTS carry_forward_expiry_months INTEGER NULL;
ALTER TABLE leave_type ADD COLUMN IF NOT EXISTS encashable BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE leave_type ADD COLUMN IF NOT EXISTS max_encashable_days_per_year DOUBLE PRECISION NULL;
ALTER TABLE leave_type ADD COLUMN IF NOT EXISTS encashment_basis VARCHAR(10) NOT NULL DEFAULT 'BASIC';
ALTER TABLE leave_type ADD COLUMN IF NOT EXISTS system_managed BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE leave_type ADD COLUMN IF NOT EXISTS credit_expiry_days INTEGER NULL;

ALTER TABLE leave_balance ADD COLUMN IF NOT EXISTS accrued_through DATE NULL;
ALTER TABLE leave_balance ADD COLUMN IF NOT EXISTS year_end_processed_at TIMESTAMP(6) WITHOUT TIME ZONE NULL;
ALTER TABLE leave_balance ADD COLUMN IF NOT EXISTS closing_balance_days DOUBLE PRECISION NULL;
ALTER TABLE leave_balance ADD COLUMN IF NOT EXISTS lapsed_days DOUBLE PRECISION NULL;

CREATE TABLE IF NOT EXISTS leave_balance_adjustment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    leave_type_id BIGINT NOT NULL REFERENCES leave_type(id),
    leave_year INTEGER NOT NULL,
    days DOUBLE PRECISION NOT NULL,
    effective_date DATE NOT NULL,
    reason VARCHAR(500) NOT NULL,
    adjusted_by_employee_id BIGINT REFERENCES employee(id)
);
CREATE INDEX IF NOT EXISTS ix_leave_adjustment_employee ON leave_balance_adjustment (company_id, employee_id, leave_type_id, leave_year);

CREATE TABLE IF NOT EXISTS comp_off_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    work_date DATE NOT NULL,
    duration VARCHAR(20) NOT NULL,
    hours DOUBLE PRECISION NULL,
    days DOUBLE PRECISION NOT NULL,
    day_type VARCHAR(20) NOT NULL,
    attendance_verified BOOLEAN NULL,
    reason VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    expires_on DATE NULL,
    decided_by_employee_id BIGINT REFERENCES employee(id),
    decided_at TIMESTAMP(6) WITHOUT TIME ZONE,
    decision_note VARCHAR(500)
);
CREATE INDEX IF NOT EXISTS ix_comp_off_employee ON comp_off_request (company_id, employee_id, status);

CREATE TABLE IF NOT EXISTS leave_encashment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    leave_type_id BIGINT NOT NULL REFERENCES leave_type(id),
    leave_year INTEGER NOT NULL,
    days DOUBLE PRECISION NOT NULL,
    reason VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    basis VARCHAR(10),
    per_day_rate NUMERIC(15, 2),
    amount NUMERIC(15, 2),
    decided_by_employee_id BIGINT REFERENCES employee(id),
    decided_at TIMESTAMP(6) WITHOUT TIME ZONE,
    decision_note VARCHAR(500),
    payroll_item_id BIGINT NULL,
    paid_at TIMESTAMP(6) WITHOUT TIME ZONE NULL
);
CREATE INDEX IF NOT EXISTS ix_leave_encashment_employee ON leave_encashment (company_id, employee_id, status);
