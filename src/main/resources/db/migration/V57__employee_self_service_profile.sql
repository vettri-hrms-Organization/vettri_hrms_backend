-- V57: employee self-service profile (Keka-style).
-- Employees keep their own contact, personal, emergency, family, education and experience details
-- up to date. Identity, bank and statutory fields change only through an HR-approved request.
-- Additive only: new nullable columns and new tables, no existing data is changed.

ALTER TABLE employee ADD COLUMN IF NOT EXISTS personal_email VARCHAR(150);
ALTER TABLE employee ADD COLUMN IF NOT EXISTS blood_group VARCHAR(5);
ALTER TABLE employee ADD COLUMN IF NOT EXISTS marital_status VARCHAR(20);
ALTER TABLE employee ADD COLUMN IF NOT EXISTS permanent_address VARCHAR(300);
ALTER TABLE employee ADD COLUMN IF NOT EXISTS emergency_contact_relation VARCHAR(40);
ALTER TABLE employee ADD COLUMN IF NOT EXISTS about_me VARCHAR(1000);

CREATE TABLE IF NOT EXISTS employee_family_member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    name VARCHAR(150) NOT NULL,
    relation VARCHAR(40) NOT NULL,
    date_of_birth DATE,
    phone VARCHAR(20),
    dependent BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS ix_employee_family_member_employee ON employee_family_member (employee_id, deleted);

CREATE TABLE IF NOT EXISTS employee_education (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    qualification VARCHAR(120) NOT NULL,
    institution VARCHAR(200) NOT NULL,
    specialization VARCHAR(150),
    start_year INTEGER,
    end_year INTEGER,
    grade VARCHAR(30)
);
CREATE INDEX IF NOT EXISTS ix_employee_education_employee ON employee_education (employee_id, deleted);

CREATE TABLE IF NOT EXISTS employee_experience (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    company_name VARCHAR(200) NOT NULL,
    job_title VARCHAR(150) NOT NULL,
    location VARCHAR(150),
    start_date DATE,
    end_date DATE,
    description VARCHAR(1000)
);
CREATE INDEX IF NOT EXISTS ix_employee_experience_employee ON employee_experience (employee_id, deleted);

-- Requested changes to identity, bank and statutory fields. changes_json holds
-- {"field": {"from": old, "to": new}} so HR sees exactly what changes.
CREATE TABLE IF NOT EXISTS profile_change_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    section VARCHAR(30) NOT NULL,
    changes_json TEXT NOT NULL,
    reason VARCHAR(500),
    status VARCHAR(20) NOT NULL,
    reviewed_by_user_id BIGINT,
    reviewed_by_name VARCHAR(150),
    review_note VARCHAR(500),
    reviewed_at TIMESTAMP(6) WITHOUT TIME ZONE
);
CREATE INDEX IF NOT EXISTS ix_profile_change_request_company ON profile_change_request (company_id, status);
CREATE INDEX IF NOT EXISTS ix_profile_change_request_employee ON profile_change_request (employee_id, status);
