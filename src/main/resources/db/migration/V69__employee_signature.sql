-- V69: saved signature pictures for e-sign. Each employee uploads (or draws) their signature once; it is stamped
-- on every document they sign. The request keeps a reference and fingerprint of the exact picture used.
-- Additive only.

CREATE TABLE IF NOT EXISTS employee_signature (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100), updated_by VARCHAR(100), deleted BOOLEAN NOT NULL DEFAULT FALSE, deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    s3_object_key VARCHAR(500) NOT NULL,
    content_sha256 VARCHAR(64) NOT NULL,
    source VARCHAR(10) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_employee_signature_employee ON employee_signature (employee_id, deleted);

ALTER TABLE signature_request ADD COLUMN IF NOT EXISTS signature_image_key VARCHAR(500);
ALTER TABLE signature_request ADD COLUMN IF NOT EXISTS signature_image_sha256 VARCHAR(64);
