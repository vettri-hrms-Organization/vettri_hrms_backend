-- V65: flexible benefit plan (reimbursement model). Components with annual limits; each employee's yearly
-- declaration carves the amount out of special allowance; bills are claimed and paid tax-free through payroll;
-- unclaimed balance is paid as taxable in March. Additive only: new tables, no existing data changes.

CREATE TABLE IF NOT EXISTS fbp_component (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    name VARCHAR(80) NOT NULL,
    description VARCHAR(300),
    annual_limit NUMERIC(12, 2) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX IF NOT EXISTS ix_fbp_component_company ON fbp_component (company_id);

CREATE TABLE IF NOT EXISTS fbp_declaration (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    financial_year INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    monthly_total NUMERIC(12, 2) NOT NULL DEFAULT 0,
    lines_json TEXT NOT NULL,
    start_month VARCHAR(7),
    reviewed_by VARCHAR(150),
    review_note VARCHAR(500),
    year_end_settled BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS ix_fbp_declaration_employee ON fbp_declaration (employee_id, financial_year);

CREATE TABLE IF NOT EXISTS fbp_claim (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    declaration_id BIGINT NOT NULL REFERENCES fbp_declaration(id),
    component_id BIGINT NOT NULL REFERENCES fbp_component(id),
    bill_date DATE NOT NULL,
    bill_reference VARCHAR(100),
    description VARCHAR(500),
    amount NUMERIC(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    review_note VARCHAR(500),
    reviewed_by VARCHAR(150),
    settled BOOLEAN NOT NULL DEFAULT FALSE,
    payroll_item_id BIGINT
);
CREATE INDEX IF NOT EXISTS ix_fbp_claim_employee ON fbp_claim (employee_id, status);
CREATE INDEX IF NOT EXISTS ix_fbp_claim_company ON fbp_claim (company_id, status);
