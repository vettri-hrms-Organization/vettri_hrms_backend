-- V64: bonus runs - a one-off, performance or statutory bonus for many employees, approved and paid through payroll.
-- Additive only: new tables, no existing data changes.

CREATE TABLE IF NOT EXISTS bonus_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    name VARCHAR(120) NOT NULL,
    bonus_type VARCHAR(20) NOT NULL,
    method VARCHAR(20) NOT NULL,
    method_value NUMERIC(14, 3),
    financial_year INTEGER,
    wage_ceiling NUMERIC(10, 2),
    payout_month VARCHAR(7) NOT NULL,
    status VARCHAR(20) NOT NULL,
    taxable BOOLEAN NOT NULL DEFAULT TRUE,
    note VARCHAR(1000),
    created_by_name VARCHAR(150),
    approved_by_name VARCHAR(150),
    approved_at TIMESTAMP(6) WITHOUT TIME ZONE
);
CREATE INDEX IF NOT EXISTS ix_bonus_batch_company ON bonus_batch (company_id, status);

CREATE TABLE IF NOT EXISTS bonus_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    batch_id BIGINT NOT NULL REFERENCES bonus_batch(id),
    employee_id BIGINT NOT NULL REFERENCES employee(id),
    basis_amount NUMERIC(14, 2),
    amount NUMERIC(14, 2) NOT NULL,
    note VARCHAR(300),
    settled BOOLEAN NOT NULL DEFAULT FALSE,
    payroll_item_id BIGINT
);
CREATE INDEX IF NOT EXISTS ix_bonus_line_batch ON bonus_line (batch_id);
CREATE INDEX IF NOT EXISTS ix_bonus_line_employee ON bonus_line (employee_id, settled);
